catalog = json.load(open(os.path.join(DATA, "lc_catalog.json"), encoding="utf-8"))
by_no = {c["no"]: c for c in catalog}

out = {"categories": {}, "hints": USER_HINTS, "all_numbers": []}
seen = []
problems = 0
for cat, items in USER_LIST.items():
    rows = []
    for no, title_from_image in items:
        c = by_no.get(no)
        if not c:
            print("!! 题号不在力扣题库中:", no, title_from_image)
            continue
        rows.append({"no": no, "title": c["title"], "slug": c["slug"], "level": c["level"], "tags": c["tags"]})
        problems += 1
        if no not in seen:
            seen.append(no)
    out["categories"][cat] = rows

out["all_numbers"] = seen
out["stats"] = {"slots": problems, "unique": len(seen)}

with open(os.path.join(DATA, "用户题单.json"), "w", encoding="utf-8") as f:
    json.dump(out, f, ensure_ascii=False, indent=1)

print(f"slots={problems} unique={len(seen)}")
for cat, rows in out["categories"].items():
    print(f"\n{cat} ({len(rows)}): " + "、".join(f"{r['no']} {r['title']}" for r in rows))
